export const LANGUAGES = Object.keys(CATALOGUE);

/** The catalogue for a language tag: exact, then its base (`pt-BR` → `pt`), then English. */
export function catalogueOf(lang) {
  const tag = String(lang ?? "en");
  return CATALOGUE[tag] ?? CATALOGUE[tag.split("-")[0]] ?? CATALOGUE.en;
}

/** A text in the language of the phone, or in English if the catalogue lacks it, with its
 *  `{holes}` filled from `values`. */
export function t(lang, key, values = {}) {
  const text = catalogueOf(lang)[key] ?? CATALOGUE.en[key] ?? key;
  return text.replace(/\{([a-z]+)\}/g, (hole, name) => (name in values ? String(values[name]) : hole));
}

/** Which way the plugin's text runs: Arabic right to left, the rest of the app's left to right. */
export function directionOf(lang) {
  return String(lang ?? "en").split("-")[0] === "ar" ? "rtl" : "ltr";
}

/**
 * The phone's date and time, as the phone's language writes them, with the time zone: what is
 * drawn under a signature. Narrow and thin spaces become plain ones, so a Latin date can be
 * written with the PDF's own Helvetica. `timeZone` is for the tests; the phone's is the default.
 */
export function formatWhen(date, lang, timeZone) {
  const options = { year: "numeric", month: "short", day: "numeric", hour: "2-digit", minute: "2-digit", timeZoneName: "short", timeZone };
  let format;
  try {
    format = new Intl.DateTimeFormat(lang, options);
  } catch {
    format = new Intl.DateTimeFormat("en", options);
  }
  return format.format(date).replace(/[   ]/g, " ");
}
